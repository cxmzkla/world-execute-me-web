/* ══════════════════════════════════════════════════════════════════
   clock.js —— 时间轴与播放状态
   这里是全片唯一的权威时钟：t 由 rAF 累加，音频被拖着去对齐 t，
   而不是反过来。因为本地 http.server 不支持 Range，audio.currentTime
   在拖动后不一定可靠；让画面相信自己的时钟，拖到哪儿都是对的。
   ══════════════════════════════════════════════════════════════════ */

export const clock = {
  t: 0,              // 当前时间（秒），0 ~ DUR
  playing: false,
  started: false,    // 是否已点击开始遮罩
  audioOK: true,     // 音频解码/播放失败时降级成纯无声播放
  freezeT: null,     // 调试：把时间钉死在某一帧
  lastSync: 0        // 上次与音频对齐的时刻（防抖，900ms 内不重复纠正）
};
