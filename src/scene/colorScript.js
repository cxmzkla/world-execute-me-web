/* ══════════════════════════════════════════════════════════════════
   colorScript.js —— 逐幕色温
   ─────────────────────────────────────────────────────────────────
   参考片之所以"高级"，很大程度是因为每一段的颜色都只有一个主张：
   冷白 → 青 → 金 → 紫 → 冷灰 → 血红 → 暖白 → 玫红 → 无彩。
   如果全程一个青色，再精细也会显得像未调色的 demo。
   这里给出一条连续曲线，供着色器与 HUD 共用。
   ══════════════════════════════════════════════════════════════════ */

/* t, r, g, b —— 数值是"颜色主张"，不是最终像素亮度 */
const KEYS = [
  [  0.00, 0.42, 0.72, 0.82 ],   // BOOT      冷白蓝，几乎无彩
  [ 16.00, 0.62, 0.90, 0.96 ],   // RUN       青白，最亮
  [ 29.70, 0.40, 0.76, 0.90 ],   // PROOF     冰蓝
  [ 44.45, 0.52, 0.70, 0.94 ],   // AC-DC     蓝紫过渡
  [ 52.00, 0.62, 0.52, 0.92 ],   //           紫
  [ 59.22, 0.92, 0.74, 0.48 ],   // DEPLOY    琥珀
  [ 74.04, 0.96, 0.80, 0.52 ],   // OBJECTS   金
  [ 88.58, 0.72, 0.56, 0.94 ],   // TRANCE    紫罗兰
  [103.49, 0.52, 0.66, 0.74 ],   // ISOLATION 冷灰蓝，饱和度掉下来
  [118.00, 0.42, 0.52, 0.58 ],   //           更冷更灰
  [131.22, 0.40, 0.16, 0.16 ],   // VOID      近黑里的暗红
  [147.66, 0.94, 0.24, 0.16 ],   // ×12       血红
  [155.00, 1.00, 0.36, 0.18 ],   //           更烫
  [161.58, 0.86, 0.74, 0.60 ],   // REBUILD   回暖白
  [177.25, 0.98, 0.52, 0.56 ],   // LOVE      玫红
  [183.40, 1.00, 0.46, 0.42 ],   //           更饱和
  [189.60, 1.00, 0.44, 0.40 ],   //           心跳结束仍是血色
  [191.36, 0.72, 0.78, 0.86 ],   // END       一刀褪回冷
  [205.90, 0.78, 0.84, 0.90 ],   //           近白
  [212.00, 0.60, 0.68, 0.74 ]
];

export const COLOR = { r:0.6, g:0.8, b:0.9 };

const hex2 = v => { const s = Math.round(Math.max(0,Math.min(1,v))*255).toString(16); return s.length<2?'0'+s:s; };

/* 每帧调用：算出当前色，同时给出 CSS 用的十六进制 */
export function colorAt(t){
  let i = 0;
  while(i < KEYS.length-2 && t > KEYS[i+1][0]) i++;
  const a = KEYS[i], b = KEYS[i+1];
  let u = (t - a[0]) / Math.max(1e-6, b[0]-a[0]);
  u = Math.max(0, Math.min(1, u));
  u = u*u*(3-2*u);
  COLOR.r = a[1] + (b[1]-a[1])*u;
  COLOR.g = a[2] + (b[2]-a[2])*u;
  COLOR.b = a[3] + (b[3]-a[3])*u;
  return COLOR;
}

/* 归一化到最亮通道 = 1，用作乘法 tint 时不会整体压暗 */
export function tintRGB(){
  const m = Math.max(COLOR.r, COLOR.g, COLOR.b, 1e-4);
  return [COLOR.r/m, COLOR.g/m, COLOR.b/m];
}

export function cssAccent(){
  return '#'+hex2(COLOR.r)+hex2(COLOR.g)+hex2(COLOR.b);
}
