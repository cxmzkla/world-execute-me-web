/* 二分查当前行号，-1 表示还没开始 */
export function lineAt(t){
  let lo=0, hi=LRC.length-1;
  if(t < LRC[0][0]) return -1;
  while(lo<hi){ const m=(lo+hi+1)>>1; if(t>=LRC[m][0]) lo=m; else hi=m-1; }
  return lo;
}
